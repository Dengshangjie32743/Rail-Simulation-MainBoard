/*
 * 将长整型转为4个字节的数组
 */
void HAL_LongConvertBytes(uint32_t ulNum, uint8_t* aucBytes)
{
    aucBytes[0] = (ulNum >> 24) & 0xFF;
    aucBytes[1] = (ulNum >> 16) & 0xFF;
    aucBytes[2] = (ulNum >> 8) & 0xFF;
    aucBytes[3] = ulNum & 0xFF;
}

/*
 * AD采集
 */
uint32_t HAL_GetAdc(void)
{
    uint32_t ulVal;

    HAL_ADC_Start(&hadc1);
    HAL_ADC_PollForConversion(&hadc1,10);
    ulVal = HAL_ADC_GetValue(&hadc1);
    HAL_ADC_Stop(&hadc1);

    return ulVal;
}

